import assert from 'node:assert/strict';
import { EventBus } from '../src/core/event-bus.js';
import { EVENT } from '../src/core/constants.js';
import { CharacterStats } from '../src/player/character-stats.js';
import { PlayerData } from '../src/player/player-data.js';
import { InventoryManager } from '../src/inventory/inventory-manager.js';
import { EquipmentManager } from '../src/inventory/equipment-manager.js';
import { LootSystem } from '../src/inventory/loot-system.js';
import { QuestManager } from '../src/quest/quest-manager.js';
import { RewardService } from '../src/rewards/reward-service.js';
import { ShopService } from '../src/economy/shop-service.js';
import { DungeonService, DUNGEON_STATES } from '../src/dungeon/dungeon-service.js';
import { validateSave } from '../src/save/data-validation.js';
import { validateIntent } from '../src/network/server-validation.js';

const events=new EventBus();
const player=new PlayerData();
const inventory=new InventoryManager(events);
const equipment=new EquipmentManager(player,inventory,events);
assert.equal(inventory.quantity('dew_vial'),2,'fresh inventory contains genuine starter items');
assert.equal(inventory.add('not-real',1),false,'unknown item ID is rejected');
assert.equal(inventory.add('dew_vial',0),false,'invalid quantity is rejected');
assert.equal(inventory.add('dew_vial',Number.NaN),false,'non-finite quantity is rejected without mutation');
assert.ok(inventory.add('verdant_blade',1));
const beforeAttack=player.stats.attack;
assert.ok(equipment.equip(inventory.findFirst('verdant_blade').entry.instanceId));
assert.ok(player.stats.attack>beforeAttack,'equipment recalculates derived attack');
assert.ok(equipment.unequip('weapon'));

const loot=new LootSystem(events,{random:()=>0});
assert.deepEqual(loot.plan('thornwalker'),[{itemId:'verdant_shard',quantity:1}],'weighted loot is deterministic with injected RNG');
assert.equal(loot.validatePlan([{itemId:'not-real',quantity:1}]),false,'invalid loot plans fail validation');
const quests=new QuestManager(events,inventory,player);
let spawnAllowed=null;
const world={spawns:{setAvailability:(callback)=>{spawnAllowed=callback;}},teleport(){},refreshSpawns(){}};
const dungeon=new DungeonService({events,player,quests,world,saved:{}});
const rewards=new RewardService({events,player,inventory,loot});

assert.ok(quests.accept('thornwatch_hunt'));
for(let index=0;index<5;index++)events.emit(EVENT.ENEMY_DEFEATED,{enemy:{data:{id:'thornwalker',xp:28,elite:false,boss:false},definition:{id:`thorn-${index}`}}});
assert.ok(quests.isReady('thornwatch_hunt'),'kill objective becomes ready, not auto-completed');
const goldBeforeTurnIn=player.gold;
assert.ok(quests.turnIn('thornwatch_hunt','arin'));
assert.ok(quests.isCompleted('thornwatch_hunt'));
assert.ok(player.hasUnlock('aurel_sanctum'),'turn-in applies data-defined unlock');
assert.ok(player.gold>goldBeforeTurnIn,'turn-in reward applies gold');
assert.ok(player.stats.level>=2,'XP reward advances level and derived progression');
assert.ok(quests.accept('sanctum_assault'));
assert.equal(spawnAllowed({id:'hub_elite_warden'}),false);
assert.ok(dungeon.enter('aurel_sanctum'),'entry validates level, quest, and unlock');
assert.equal(dungeon.state('aurel_sanctum'),DUNGEON_STATES.ENTERED);
assert.equal(spawnAllowed({id:'hub_elite_warden'}),true);
assert.equal(spawnAllowed({id:'hub_boss_aurel'}),false);
events.emit(EVENT.ENEMY_DEFEATED,{enemy:{data:{id:'rootwarden',xp:160,elite:true,boss:false},definition:{id:'hub_elite_warden'}}});
assert.equal(dungeon.state('aurel_sanctum'),DUNGEON_STATES.ELITE_DEFEATED);
assert.equal(spawnAllowed({id:'hub_boss_aurel'}),true);
events.emit(EVENT.ENEMY_DEFEATED,{enemy:{data:{id:'thornheart_titan',xp:750,elite:true,boss:true},definition:{id:'hub_boss_aurel'}}});
assert.equal(dungeon.state('aurel_sanctum'),DUNGEON_STATES.COMPLETED);
assert.ok(quests.isReady('sanctum_assault'));
assert.ok(quests.turnIn('sanctum_assault','arin'));
assert.ok(player.hasUnlock('emberfall'));

const shop=new ShopService(events,player,inventory);
const goldBeforeBuy=player.gold;
assert.ok(shop.buy('rootforge','dew_vial',1));
assert.equal(player.gold,goldBeforeBuy-18,'shop ignores caller price and charges catalog value');
assert.ok(shop.sell(inventory.findFirst('dew_vial').entry.instanceId,1));
assert.equal(shop.buy('rootforge','not-real',1),false);
assert.equal(shop.buy('rootforge','dew_vial',0),false,'shop rejects invalid quantity');
const goldBeforeInvalidReward=player.gold;
assert.equal(rewards.grant({xp:-1,gold:999,items:[]}),false,'invalid reward cannot mutate progression');
assert.equal(player.gold,goldBeforeInvalidReward);

const levelStats=new CharacterStats({level:1,xp:99,health:1,energy:0});
assert.deepEqual(levelStats.gainXp(1),[2]);
assert.equal(levelStats.health,levelStats.maxHealth);
assert.ok(levelStats.unlockedSkills.has('ultimate'));
const v1=validateSave({version:1,player:{stats:{level:2,xp:4},gold:90,equipment:{weapon:'frontier_blade'}},inventory:{items:{dew_vial:3,frontier_blade:1}},quests:{active:['breach_line']},world:{}});
assert.equal(v1.version,2,'v1 save migrates to v2');
assert.equal(v1.inventory.items.dew_vial,3);
assert.deepEqual(v1.quests.active,[],'unknown legacy quest is discarded');
const v2=validateSave({version:2,player:{...player.snapshot(),dungeonProgress:dungeon.snapshot()},inventory:inventory.snapshot(),quests:quests.snapshot(),world:{}});
assert.equal(v2.player.dungeonProgress.aurel_sanctum.state,'Completed');
const reloadedPlayer=new PlayerData(v2.player);
const reloadedInventory=new InventoryManager(new EventBus(),v2.inventory);
assert.equal(reloadedPlayer.gold,player.gold,'validated save restores Gold');
assert.equal(reloadedPlayer.hasUnlock('emberfall'),true,'validated save restores world unlocks');
assert.equal(reloadedInventory.quantity('dew_vial'),inventory.quantity('dew_vial'),'validated save restores ID quantities');
assert.equal(validateIntent({type:'combat',action:'heavy',targetId:'enemy_1'}).valid,true);
assert.equal(validateIntent({type:'combat',action:'heavy',targetId:'enemy_1',xp:9}).valid,false,'client reward injection is rejected');
console.log('Phase 4 RPG flow tests passed.');
